# 제목에서 찾을 낱말은 2자 미만이면 쓰지 않는다.
# "물"이 박물관에, "열"이 열람실에 걸리는 식의 사고를 막는다.
MIN_KW = 2


def flat():
    """{이름: {group, ncs, kw, alias}} 형태로 펴서 돌려준다."""
    out = {}
    for gname, items in GROUPS:
        for name, ncs, kw, _alias in items:
            out[name] = {
                "group": gname,
                "ncs": ncs,
                "kw": [k for k in kw if len(k) >= MIN_KW],
                "alias": sorted(set([name] + ALIAS_EXTRA.get(name, []))),
            }
    return out
